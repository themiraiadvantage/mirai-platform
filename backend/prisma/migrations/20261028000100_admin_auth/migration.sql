CREATE TYPE "StaffRole" AS ENUM ('SUPER_ADMIN', 'LISTING_MANAGER', 'VERIFICATION_REVIEWER', 'PAYMENT_SUPPORT', 'DOCUMENT_ADMINISTRATOR', 'SITE_CHECK_CONTRIBUTOR');

ALTER TABLE "User"
ADD COLUMN "staffRole" "StaffRole",
ADD COLUMN "staffActive" BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE "StaffInvitation" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "email" TEXT NOT NULL UNIQUE,
  "name" TEXT NOT NULL,
  "role" "StaffRole" NOT NULL,
  "tokenHash" TEXT NOT NULL UNIQUE,
  "expiresAt" TIMESTAMP(3) NOT NULL,
  "acceptedAt" TIMESTAMP(3),
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "invitedById" TEXT REFERENCES "User"("id") ON DELETE RESTRICT ON UPDATE CASCADE
);
